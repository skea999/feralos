// GenerateFstab writes /etc/fstab matching the reference skeaSimpleServer layout.
// Uses LABEL=myroot for btrfs subvolumes, LABEL=EFI* for EFI, LABEL=swap-* for swap.
//
// IMPORTANT: btrfs compression is set per-subvolume via 'btrfs property set'.
// The compress= mount option is FS-wide only — first mount's options apply.
// NoCoW subvolumes use 'chattr +C' + 'btrfs property set compression none'.
func GenerateFstab(conf *config.Config) error {
	u := conf.User
	i := conf.Internal

	if len(u.Disks) < 2 {
		return fmt.Errorf("btrfsStandardServer layout requires at least 2 disks, found: %d", len(u.Disks))
	}

	d1 := u.Disks[0]
	d2 := u.Disks[1]
	sp1 := getPartitionSpacer(d1)
	sp2 := getPartitionSpacer(d2)

	fmt.Println("[INFO] Writing /etc/fstab for LUKS + Btrfs RAID1 Server Layout...")

	fstabPath := i.ChrootDir + "/etc/fstab"
	if err := os.MkdirAll(i.ChrootDir+"/etc", 0755); err != nil {
		return fmt.Errorf("failed to create /etc directory: %w", err)
	}

	file, err := os.Create(fstabPath)
	if err != nil {
		return fmt.Errorf("failed to create fstab: %w", err)
	}
	defer func() {
		if cerr := file.Close(); cerr != nil && err == nil {
			err = cerr
		}
	}()

	// Helper to get disk suffix (e.g., "sda", "nvme0n1")
	diskSuffix := func(path string) string {
		parts := strings.Split(path, "/")
		return parts[len(parts)-1]
	}

	// Header comment
	if _, err := file.WriteString("# Generated by FeralOS Installer\n"); err != nil {
		return err
	}
	if _, err := file.WriteString("# btrfs compression: per-subvolume via 'btrfs property set compression none'\n"); err != nil {
		return err
	}
	if _, err := file.WriteString("# NoCoW subvolumes: set via 'chattr +C <path>' during installation\n"); err != nil {
		return err
	}
	if _, err := file.WriteString("# These properties are set during installation and persist across reboots\n\n"); err != nil {
		return err
	}

	// 1. Btrfs subvolumes on RAID1 (LABEL=myroot)
	// Compression is set per-subvolume via btrfs property set (not mount options).
	// The compress= mount option is FS-wide only — first mount's options apply.
	// NoCoW subvolumes: 'chattr +C' + 'btrfs property set compression none'
	subvols := []struct {
		Name    string
		Path    string
		Options string
		NoCoW   bool
	}{
		{Name: "@", Path: "/", Options: "compress=zstd:3,autodefrag,ssd,subvol=@"},
		{Name: "@swap", Path: "/swap", Options: "ssd,compress=none,subvol=@swap", NoCoW: true},
		{Name: "@home", Path: "/home", Options: "compress=zstd:3,autodefrag,ssd,subvol=@home"},
		{Name: "@opt", Path: "/opt", Options: "compress=zstd:3,autodefrag,ssd,subvol=@opt"},
		{Name: "@root", Path: "/root", Options: "compress=zstd:3,autodefrag,ssd,subvol=@root"},
		{Name: "@srv", Path: "/srv", Options: "autodefrag,ssd,nodev,noexec,nosuid,subvol=@srv", NoCoW: true},
		{Name: "@tmp", Path: "/tmp", Options: "compress=zstd:3,autodefrag,ssd,noexec,nosuid,subvol=@tmp"},
		{Name: "@var", Path: "/var", Options: "compress=zstd:3,autodefrag,ssd,subvol=@var"},
		{Name: "@var-lib-ex", Path: "/var/lib/ex", Options: "autodefrag,ssd,nodev,noexec,nosuid,subvol=@var-lib-ex", NoCoW: true},
		{Name: "@var-lib-libvirt", Path: "/var/lib/libvirt", Options: "compress=zstd:3,autodefrag,ssd,subvol=@var-lib-libvirt"},
		{Name: "@var-lib-incus", Path: "/var/lib/incus", Options: "compress=zstd:3,autodefrag,ssd,subvol=@var-lib-incus"},
		{Name: "@var-lib-containerd", Path: "/var/lib/containerd", Options: "compress=zstd:3,autodefrag,ssd,subvol=@var-lib-containerd"},
		{Name: "@var-lib-docker", Path: "/var/lib/docker", Options: "compress=zstd:3,autodefrag,ssd,subvol=@var-lib-docker"},
		{Name: "@var-lib-containers", Path: "/var/lib/containers", Options: "compress=zstd:3,autodefrag,ssd,subvol=@var-lib-containers"},
		{Name: "@var-lib-vector", Path: "/var/lib/vector", Options: "compress=zstd:3,autodefrag,ssd,subvol=@var-lib-vector"},
		{Name: "@var-cache", Path: "/var/cache", Options: "compress=zstd:3,autodefrag,ssd,subvol=@var-cache"},
		{Name: "@var-log", Path: "/var/log", Options: "autodefrag,ssd,nodev,noexec,nosuid,subvol=@var-log", NoCoW: true},
		{Name: "@var-opt", Path: "/var/opt", Options: "compress=zstd:3,autodefrag,ssd,subvol=@var-opt"},
		{Name: "@var-spool", Path: "/var/spool", Options: "autodefrag,ssd,nodev,noexec,nosuid,subvol=@var-spool", NoCoW: true},
		{Name: "@var-tmp", Path: "/var/tmp", Options: "autodefrag,ssd,nodev,noexec,nosuid,subvol=@var-tmp", NoCoW: true},
		{Name: "@usr-local", Path: "/usr/local", Options: "compress=zstd:3,autodefrag,ssd,subvol=@usr-local"},
		{Name: "@boot", Path: "/boot", Options: "compress=zstd:3,autodefrag,ssd,subvol=@boot"},
		// Nix package manager (always present — Nix can be enabled later)
		{Name: "@nix-store", Path: "/nix/store", Options: "compress=zstd:3,autodefrag,ssd,subvol=@nix-store"},
		{Name: "@nix-var-nix", Path: "/nix/var/nix", Options: "compress=zstd:3,autodefrag,ssd,subvol=@nix-var-nix"},
		{Name: "@nix-var-log", Path: "/nix/var/log", Options: "autodefrag,ssd,nodev,noexec,nosuid,subvol=@nix-var-log", NoCoW: true},
		{Name: "@nix-var-nix-build", Path: "/nix/var/nix/build", Options: "compress=zstd:3,autodefrag,ssd,subvol=@nix-var-nix-build"},
		// Btrbk backup
		{Name: "@btrbk", Path: "/btrbk", Options: "compress=zstd:3,autodefrag,ssd,subvol=@btrbk"},
	}

	for _, s := range subvols {
		opts := s.Options
		if s.NoCoW {
			opts += ",nodatacow"
			comment := fmt.Sprintf("# %s: NoCoW via nodatacow + btrfs property set compression none\n", s.Name)
			if _, err := file.WriteString(comment); err != nil {
				return fmt.Errorf("failed to write fstab comment for %s: %w", s.Name, err)
			}
		}
		line := fmt.Sprintf("LABEL=myroot  %-25s  btrfs  %-70s  0  0\n", s.Path, opts)
		if _, err := file.WriteString(line); err != nil {
			return fmt.Errorf("failed to write fstab entry for %s: %w", s.Name, err)
		}
	}

	// 2. EFI Partitions
	s1 := strings.ToUpper(diskSuffix(d1))
	s2 := strings.ToUpper(diskSuffix(d2))

	if _, err := fmt.Fprintf(file, "\nLABEL=EFI%-10s  /boot/efi               vfat   rw,noatime,fmask=0022,dmask=0022,codepage=437,iocharset=ascii,shortname=mixed,utf8,errors=remount-ro  0  2\n", s1); err != nil {
		return fmt.Errorf("failed to write fstab EFI1 entry: %w", err)
	}
	if _, err := fmt.Fprintf(file, "LABEL=EFI%-10s  /boot/efi2              vfat   rw,noatime,fmask=0022,dmask=0022,codepage=437,iocharset=ascii,shortname=mixed,utf8,errors=remount-ro  0  2\n", s2); err != nil {
		return fmt.Errorf("failed to write fstab EFI2 entry: %w", err)
	}

	// 3. Swap (LUKS-backed dm-crypt mappers — use /dev/mapper paths, not
	// LABEL: busybox swapon -a can't resolve by-label symlinks at swap time)
	s1lower := strings.ToLower(diskSuffix(d1))
	s2lower := strings.ToLower(diskSuffix(d2))

	if _, err := fmt.Fprintf(file, "\n/dev/mapper/swap-%s%s  none                    swap   defaults,sw,pri=2  0  0\n", s1lower, sp1+"3"); err != nil {
		return fmt.Errorf("failed to write fstab swap1 entry: %w", err)
	}
	if _, err := fmt.Fprintf(file, "/dev/mapper/swap-%s%s  none                    swap   defaults,sw,pri=2  0  0\n", s2lower, sp2+"3"); err != nil {
		return fmt.Errorf("failed to write fstab swap2 entry: %w", err)
	}

	// 4. Data Partitions
	if _, err := fmt.Fprintf(file, "\nLABEL=data-%s%s  /data/data-%s%s        btrfs  defaults  0  0\n", s1lower, sp1+"4", s1lower, sp1+"4"); err != nil {
		return fmt.Errorf("failed to write fstab data1 entry: %w", err)
	}
	if _, err := fmt.Fprintf(file, "LABEL=data-%s%s  /data/data-%s%s        btrfs  defaults  0  0\n", s2lower, sp2+"4", s2lower, sp2+"4"); err != nil {
		return fmt.Errorf("failed to write fstab data2 entry: %w", err)
	}

	return nil
}

// WriteEfiSyncHook writes an APK commit hook that syncs /boot/efi to /boot/efi2
// after kernel upgrades. Only for dual-disk layouts (btrfsStandardServer).
// Writes via host path (hostPhase contract).
func WriteEfiSyncHook(conf *config.Config) error {
	chroot := conf.Internal.ChrootDir

	efiHook := `#!/bin/sh

STAGE="${1}"
targetCmd="upgrade"
targetPkg="linux-lts"

if [ "${STAGE}" = "post-commit" ] && [ "${APK_COMMAND}" = "${targetCmd}" ]; then
    echo "Executing ${targetPkg}-raid-efi.sh post-commit hook because apk is doing the command ${targetCmd}... "

    latestLog=$(ls -t /var/log/apk/* | head -n 1)

    if [ -f "${latestLog}" ]; then
        if grep -qE "install|upgrade" "${latestLog}" | grep -q "${targetPkg}"; then
            echo "Found ${targetPkg}. Executing script now... "
            rsync -a --delete /boot/efi/ /boot/efi2/
        else
            echo "${targetPkg} not found. "
        fi
    else
        echo "Warning: Log file not found. "
    fi
fi

exit 0`
	escapedEfiHook := strings.ReplaceAll(efiHook, "'", "'\\''")
	hookCmd := fmt.Sprintf("mkdir -p %s/etc/apk/commit_hooks.d && echo '%s' > %s/etc/apk/commit_hooks.d/copy-efi.sh && chmod 755 %s/etc/apk/commit_hooks.d/copy-efi.sh", chroot, escapedEfiHook, chroot, chroot)
	if _, err := shell.ExecuteCmd("", hookCmd); err != nil {
		return fmt.Errorf("failed to write EFI sync hook: %w", err)
	}

	fmt.Println("[INFO] EFI sync hook written (dual-disk post-upgrade sync)")
	return nil
}
