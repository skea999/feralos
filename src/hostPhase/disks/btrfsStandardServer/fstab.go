package btrfsStandardServer

import (
	"alpineInstaller/utility"
	"fmt"
	"os"
	"strings"
)

func GenerateFstabWithLabels(conf *utility.Config) error {
	u := conf.User
	i := conf.Internal

	// Safety check to avoid crash if disk list is empty
	if len(u.Disks) < 2 {
		return fmt.Errorf("btrfsStandardServer layout requires at least 2 disks, found: %d", len(u.Disks))
	}

	fmt.Println("[INFO] Writing /etc/fstab for RAID1 Server Layout...")

	fstabPath := i.ChrootDir + "/etc/fstab"
	if err := os.MkdirAll(i.ChrootDir+"/etc", 0755); err != nil {
		return fmt.Errorf("failed to create /etc directory: %w", err)
	}

	file, err := os.Create(fstabPath)
	if err != nil {
		return fmt.Errorf("failed to create fstab: %w", err)
	}
	defer func() {
		if cerr := file.Close(); cerr != nil && err == nil {
			err = cerr
		}
	}()

	getDiskSuffix := func(path string) string {
		parts := strings.Split(path, "/")
		return strings.ToUpper(parts[len(parts)-1])
	}

	if _, err := file.WriteString("# Generated by Alpine Go Installer (RAID1 Server)\n"); err != nil {
		return fmt.Errorf("failed to write fstab header: %w", err)
	}
	if _, err := file.WriteString("# <file system> <mount point> <type> <options> <dump> <pass>\n\n"); err != nil {
		return fmt.Errorf("failed to write fstab header: %w", err)
	}

	// 1. Subvolumes on RAID (Label: root)
	subvols := []Subvolume{
		{Name: "@", Path: "/", Options: "compress=zstd:3,autodefrag,ssd"},
		{Name: "@home", Path: "/home", Options: "compress=zstd:3,autodefrag,ssd"},
		{Name: "@opt", Path: "/opt", Options: "compress=zstd:3,autodefrag,ssd"},
		{Name: "@root", Path: "/root", Options: "compress=zstd:3,autodefrag,ssd"},
		{Name: "@srv", Path: "/srv", Options: "nodev,noexec,nosuid,nodatacow"},
		{Name: "@tmp", Path: "/tmp", Options: "noexec,nosuid,compress=zstd:3,autodefrag,ssd"},
		{Name: "@var", Path: "/var", Options: "compress=zstd:3,autodefrag,ssd"},
		{Name: "@var-log", Path: "/var/log", Options: "nodev,noexec,nosuid,nodatacow"},
		{Name: "@usr-local", Path: "/usr/local", Options: "compress=zstd:3,autodefrag,ssd"},
		{Name: "@swap", Path: "/swap", Options: "autodefrag,ssd,nodatacow"},
	}

	for _, s := range subvols {
		mountPoint := s.Path
		if mountPoint == "" {
			mountPoint = "/"
		}
		line := fmt.Sprintf("LABEL=root  %-20s  btrfs  subvol=%s,%s  0  0\n",
			mountPoint, s.Name, s.Options)
		if _, err := file.WriteString(line); err != nil {
			return fmt.Errorf("failed to write fstab entry for %s: %w", s.Name, err)
		}
	}

	// 2. Boot (Label: boot - defined on /dev/md0p1)
	if _, err := file.WriteString("LABEL=boot  /boot                btrfs  defaults              0  2\n"); err != nil {
		return fmt.Errorf("failed to write fstab boot entry: %w", err)
	}

	// 3. EFI Partitions (Dynamic from first two disks in list)
	// u.Disks[0] replaces u.Disk1 | u.Disks[1] replaces u.Disk2
	labelEfi1 := "EFI" + getDiskSuffix(u.Disks[0])
	labelEfi2 := "EFI" + getDiskSuffix(u.Disks[1])

	if _, err := fmt.Fprintf(file, "LABEL=%-10s  /boot/efi            vfat   umask=0077,shortname=winnt  0  2\n", labelEfi1); err != nil {
		return fmt.Errorf("failed to write fstab EFI1 entry: %w", err)
	}
	if _, err := fmt.Fprintf(file, "LABEL=%-10s  /boot/efi2           vfat   umask=0077,shortname=winnt  0  2\n", labelEfi2); err != nil {
		return fmt.Errorf("failed to write fstab EFI2 entry: %w", err)
	}

	// 4. External Data Partitions (Fourth partitions of physical disks)
	suffix1 := strings.ToLower(getDiskSuffix(u.Disks[0]))
	suffix2 := strings.ToLower(getDiskSuffix(u.Disks[1]))

	if _, err := fmt.Fprintf(file, "LABEL=data-%-5s  /data/data-%-10s  btrfs  compress=zstd:3       0  2\n", suffix1, suffix1); err != nil {
		return fmt.Errorf("failed to write fstab data1 entry: %w", err)
	}
	if _, err := fmt.Fprintf(file, "LABEL=data-%-5s  /data/data-%-10s  btrfs  compress=zstd:3       0  2\n", suffix2, suffix2); err != nil {
		return fmt.Errorf("failed to write fstab data2 entry: %w", err)
	}

	return nil
}
