// yamlKeys marshals v and returns the serialized yaml key set — the same
// shape the /opt/feralos/config.yaml file really carries.
func yamlKeys(t *testing.T, v any) map[string]bool {
	t.Helper()
	data, err := yaml.Marshal(v)
	if err != nil {
		t.Fatalf("marshal: %v", err)
	}
	var asMap map[string]any
	if err := yaml.Unmarshal(data, &asMap); err != nil {
		t.Fatalf("unmarshal to map: %v", err)
	}
	out := make(map[string]bool, len(asMap))
	for k := range asMap {
		out[k] = true
	}
	return out
}

// fixtureInstallConfig returns a fully populated private struct: zero-value
// slices could otherwise hide key drift (a dropped field never serializes).
func fixtureInstallConfig() InstallConfig {
	return InstallConfig{
		DiskLayout:    "btrfsStandard",
		Disks:         []string{"/dev/sda"},
		LuksUUIDs:     []string{"1a2b3c4d-5e6f-7a8b-9c0d-1e2f3a4b5c6d"},
		UserName:      "skea999",
		Hostname:      "feral-host",
		Mirror:        "https://dl-cdn.alpinelinux.org/alpine",
		Branch:        "v3.24",
		KernelPackage: "linux-lts",
		KernelFlavor:  "lts",
	}
}

// TestInstallConfigYAMLKeysMatchLib pins the private struct against the
// writer's wire format (utils/firstboot.InstallConfig — single author of
// /opt/feralos/config.yaml): every key this binary must not lose a
// typo-level rename silently breaks the reader. The private struct
// intentionally carries a SUBSET of the lib keys (it consumes no
// password/podman/webmin values) — subset-of is the drift guard.
func TestInstallConfigYAMLKeysMatchLib(t *testing.T) {
	libKeys := yamlKeys(t, firstboot.InstallConfig{
		DiskLayout:      "btrfsStandard",
		Disks:           []string{"/dev/sda"},
		LuksUUIDs:       []string{"1a2b3c4d-5e6f-7a8b-9c0d-1e2f3a4b5c6d"},
		UserName:        "skea999",
		Password:        "pass",
		Hostname:        "feral-host",
		Mirror:          "x",
		Branch:          "v3.24",
		KernelPackage:   "linux-lts",
		KernelFlavor:    "lts",
		EnablePodman:    true,
		EnableWebmin:    true,
		WebminListenAll: true,
	})
	if len(libKeys) == 0 {
		t.Fatal("lib InstallConfig serialized no keys — struct emptied?")
	}
	ownKeys := yamlKeys(t, fixtureInstallConfig())
	for k := range ownKeys {
		if !libKeys[k] {
			t.Errorf("tpm InstallConfig yaml key %q not written by the lib InstallConfig (wire drift) — lib set: %v", k, libKeys)
		}
	}

	// Wire compat: a config written by the lib must parse without error.
	data, err := yaml.Marshal(firstboot.InstallConfig{})
	if err != nil {
		t.Fatalf("marshal lib: %v", err)
	}
	var back InstallConfig
	if err := yaml.Unmarshal(data, &back); err != nil {
		t.Errorf("lib-written config unparseable by tpm InstallConfig: %v", err)
	}
}

// TestFilterCmdlineComments pins the marker filter for efi-mkuki.
func TestFilterCmdlineComments(t *testing.T) {
	tests := []struct {
		name    string
		content string
		want    string
	}{
		{
			name:    "marker line dropped",
			content: "rd.luks.name=1a2b3c4d-5e6f-7a8b-9c0d-1e2f3a4b5c6d=root quiet\n# Generated by FeralOS Installer\n",
			want:    "rd.luks.name=1a2b3c4d-5e6f-7a8b-9c0d-1e2f3a4b5c6d=root quiet",
		},
		{
			name:    "no marker unchanged",
			content: "quiet root=/dev/mapper/root rw\n",
			want:    "quiet root=/dev/mapper/root rw",
		},
		{
			name:    "only comments → empty",
			content: "# Generated by FeralOS Installer\n",
			want:    "",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := filterCmdlineComments(tt.content); got != tt.want {
				t.Errorf("filterCmdlineComments(%q) = %q, want %q", tt.content, got, tt.want)
			}
		})
	}
}

// TestShellSingleQuote pins the POSIX single-quote embedding used at the
// efi-mkuki cmdline assignment: plain values keep the literal (the argv
// efi-mkuki sees stays identical to the old direct `-c '%s'` form), an
// embedded single quote survives via the `'\”` escape.
func TestShellSingleQuote(t *testing.T) {
	if got := shellSingleQuote("quiet rw"); got != "'quiet rw'" {
		t.Errorf("shellSingleQuote(plain) = %q, want %q", got, "'quiet rw'")
	}
	if got := shellSingleQuote("a'b"); got != `'a'\''b'` {
		t.Errorf("shellSingleQuote(embedded quote) = %q, want %q", got, `'a'\''b'`)
	}
}

// TestRepoDirBase pins the edge-base derivation: the last TWO path
// segments (branch/repo) are stripped, so v3.24/main and v3.24/community
// both land on the mirror root — the shape installClevis needs to build
// <mirror>/edge/{main,community,testing}.
func TestRepoDirBase(t *testing.T) {
	for _, repo := range []string{
		"https://dl-cdn.alpinelinux.org/alpine/v3.24/main",
		"https://dl-cdn.alpinelinux.org/alpine/v3.24/community",
	} {
		base, ok := repoDirBase(repo)
		if !ok {
			t.Errorf("repoDirBase(%q): unexpected not-ok", repo)
			continue
		}
		if base != "https://dl-cdn.alpinelinux.org/alpine" {
			t.Errorf("repoDirBase(%q) base = %q", repo, base)
		}
	}
	if _, ok := repoDirBase("http:"); ok {
		t.Error("degenerate url must report not-ok")
	}
}
