package internal

import (
	"feralos/src/utils/config"
	"feralos/src/utils/misc"
	"feralos/src/utils/shell"
	"fmt"
	"strings"
)

// BuildUKI builds an unsigned Unified Kernel Image and deploys it to both EFI partitions.
func BuildUKI(conf *config.Config) error {
	shell.SetCaller("uki")
	chroot := conf.Internal.ChrootDir
	u := conf.User

	fmt.Println("[INFO] Building and deploying UKI...")

	// Kernel flavor + microcode images from the rules (kernel.flavor,
	// microcode map): vmlinuz-<flavor>, booster-<flavor>.img,
	// linux-<flavor>.efi naming preserved; empty microcode image = no
	// microcode in the UKI.
	flavor := conf.Internal.Kernel.Flavor
	ucodeImg := ""
	cpuInfo, _ := shell.ExecuteCmd(chroot, "cat /proc/cpuinfo")
	if strings.Contains(cpuInfo, "AMD") {
		ucodeImg = conf.Internal.Microcode["amd"].Image
	} else if strings.Contains(cpuInfo, "GenuineIntel") {
		ucodeImg = conf.Internal.Microcode["intel"].Image
	}
	fmt.Printf("[DEBUG] Microcode: %s\n", ucodeImg)

	boosterImg := fmt.Sprintf("/boot/booster-%s.img", flavor)
	ukiEfi := fmt.Sprintf("linux-%s.efi", flavor)
	vmlinuz := fmt.Sprintf("/boot/vmlinuz-%s", flavor)

	if _, err := shell.ExecuteCmd(chroot, fmt.Sprintf("ALPINE_KERNEL=$(ls /lib/modules/ | head -1) && booster build --force --kernel-version \"${ALPINE_KERNEL}\" %s", boosterImg)); err != nil {
		return fmt.Errorf("booster build failed: %w", err)
	}

	if _, err := shell.ExecuteCmd(chroot, "mkdir -p /boot/efi/Alpine"); err != nil {
		return fmt.Errorf("failed to create EFI output directory: %w", err)
	}

	// Comment lines (the "Generated by FeralOS Installer" marker written
	// under the cmdline for re-run detection) must not ride into the UKI
	// kernel cmdline — same grep -v filter as the boot.go hook and the
	// tpm/secureboot first-boot rebuilds.
	ukiCmd := "CMDLINE=$(grep -v '^#' /etc/kernel/cmdline) && KERNEL_VER=$(ls /lib/modules/ | head -1) && "
	if ucodeImg != "" {
		ukiCmd += fmt.Sprintf("efi-mkuki -k \"${KERNEL_VER}\" -c \"${CMDLINE}\" -o /boot/efi/Alpine/%s %s %s %s", ukiEfi, vmlinuz, ucodeImg, boosterImg)
	} else {
		ukiCmd += fmt.Sprintf("efi-mkuki -k \"${KERNEL_VER}\" -c \"${CMDLINE}\" -o /boot/efi/Alpine/%s %s %s", ukiEfi, vmlinuz, boosterImg)
	}
	if _, err := shell.ExecuteCmd(chroot, ukiCmd); err != nil {
		return fmt.Errorf("efi-mkuki failed: %w", err)
	}

	if _, err := shell.ExecuteCmd(chroot, fmt.Sprintf("mkdir -p /boot/efi/EFI/BOOT && cp -af /boot/efi/Alpine/%s /boot/efi/EFI/BOOT/BOOTX64.EFI", ukiEfi)); err != nil {
		return fmt.Errorf("failed to create fallback BOOTX64.EFI: %w", err)
	}

	// Mirror to secondary ESP (only if /boot/efi2 exists — dual-disk layouts)
	if _, err := shell.ExecuteCmd(chroot, fmt.Sprintf("if [ -d /boot/efi2 ]; then cp -af /boot/efi/. /boot/efi2/ && mkdir -p /boot/efi2/EFI/BOOT && cp -af /boot/efi2/Alpine/%s /boot/efi2/EFI/BOOT/BOOTX64.EFI; fi", ukiEfi)); err != nil {
		return fmt.Errorf("failed to mirror to efi2: %w", err)
	}

	if len(u.Disks) >= 2 {
		d1 := u.Disks[0]
		d2 := u.Disks[1]
		// utils/misc owns the spacer (exported — setsdisk.go); the former
		// unexported copy here was byte-identical.
		sp1 := misc.GetPartitionSpacer(d1)
		sp2 := misc.GetPartitionSpacer(d2)

		if _, err := shell.ExecuteCmd(chroot, fmt.Sprintf("efibootmgr --disk %s --part 1 --create --label 'Alpine Linux' --loader /Alpine/%s --verbose || true", d1+sp1, ukiEfi)); err != nil {
			fmt.Printf("[WARNING] efibootmgr primary failed: %v\n", err)
		}
		if _, err := shell.ExecuteCmd(chroot, fmt.Sprintf("efibootmgr --disk %s --part 1 --create --label 'Alpine Linux Backup' --loader /Alpine/%s --verbose || true", d2+sp2, ukiEfi)); err != nil {
			fmt.Printf("[WARNING] efibootmgr backup failed: %v\n", err)
		}
	}

	if _, err := shell.ExecuteCmd(chroot, "efibootmgr -v || true"); err != nil {
		fmt.Printf("[WARNING] efibootmgr listing failed: %v\n", err)
	}

	return nil
}
