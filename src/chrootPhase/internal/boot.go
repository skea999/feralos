package internal

import (
	"feralos/src/utils/config"
	"feralos/src/utils/shell"
	"fmt"
	"strings"
)

// SetupBoot writes booster config, kernel cmdline, and kernel hooks.
func SetupBoot(conf *config.Config) error {
	chroot := conf.Internal.ChrootDir
	u := conf.User

	// 1. Write final kernel cmdline
	fmt.Println("[INFO] Writing final kernel cmdline...")
	finalCmdline := strings.Join(u.KernelCmdline, " ")
	if u.EnableDebug {
		// Test-only: serial console lets the harness watch boot output and
		// answer the LUKS passphrase prompt. Real hardware stays clean.
		finalCmdline += " console=ttyS0,115200"
	}
	if u.EnableDinit {
		finalCmdline += " init=/usr/libexec/dinit/init"
		// Full service status trail (start/stop/fail, timestamps) to a file:
		// once login.target (runs-on-console) takes the console, dinit's own
		// output is inhibited — the file keeps the complete history. /run
		// exists from the initramfs (written before /var/log is mounted).
		// The dinit-boot-log service mirrors it to /var/log/dinit/boot.log
		// (vector source + logrotate). Upstream wrapper param:
		// dinit_log_file= -> --log-file.
		finalCmdline += " dinit_log_file=/run/dinit-boot.log"
	}
	if _, err := shell.ExecuteCmd(chroot, "mkdir -p /etc/kernel"); err != nil {
		return fmt.Errorf("failed to create /etc/kernel directory: %w", err)
	}
	if err := shell.WriteFile(chroot, "/etc/kernel/cmdline", []byte(finalCmdline+"\n"), 0644); err != nil {
		return fmt.Errorf("failed to write final kernel cmdline: %w", err)
	}
	if err := shell.WriteFileAppend(chroot, "/etc/kernel/cmdline", []byte("# Generated by FeralOS Installer\n"), 0644); err != nil {
		return fmt.Errorf("failed to append kernel cmdline marker: %w", err)
	}

	// 2. Write booster.yaml
	fmt.Println("[INFO] Writing booster configuration...")
	forceLoadModules := strings.Join(u.Modules, ",")
	// Tunables from the rules (boosterConfig): compression, extra_files,
	// mount_timeout and the network.dhcp sub-block (dhcp: false renders
	// "off" — enable_lvm/enable_mdraid/append_all_modaliases stay static).
	dhcp := "off"
	if conf.Internal.BoosterConfig.Network.Dhcp {
		dhcp = "on"
	}
	boosterYaml := fmt.Sprintf(`compression: %s
enable_lvm: false
enable_mdraid: false
network:
  dhcp: %s
modules_force_load: %s
mount_timeout: %s
extra_files: %s
append_all_modaliases: true`,
		conf.Internal.BoosterConfig.Compression, dhcp, forceLoadModules,
		conf.Internal.BoosterConfig.MountTimeout, conf.Internal.BoosterConfig.ExtraFiles)
	if err := shell.WriteFile(chroot, "/etc/booster.yaml", []byte(boosterYaml+"\n"), 0644); err != nil {
		return fmt.Errorf("failed to write booster.yaml: %w", err)
	}
	if err := shell.WriteFileAppend(chroot, "/etc/booster.yaml", []byte("# Generated by FeralOS Installer\n"), 0644); err != nil {
		return fmt.Errorf("failed to append booster.yaml marker: %w", err)
	}

	// 3. Write kernel hook
	if err := writeBoosterHook(conf); err != nil {
		return fmt.Errorf("booster hook failed: %w", err)
	}

	return nil
}

// writeBoosterHook writes the apk kernel hook that builds the initramfs and
// assembles the UKI. Microcode image paths come from the rules (microcode
// map) — the kernel FLAVOR stays runtime-driven ($1 from the apk hook
// invocation), so vmlinuz-<flavor> / linux-<flavor>.efi naming is preserved.
// An empty microcode image simply makes its branch test false (no microcode).
func writeBoosterHook(conf *config.Config) error {
	chroot := conf.Internal.ChrootDir
	amdUcode := conf.Internal.Microcode["amd"].Image
	intelUcode := conf.Internal.Microcode["intel"].Image
	fmt.Println("[INFO] Writing booster kernel hook...")

	if _, err := shell.ExecuteCmd(chroot, "mkdir -p /etc/kernel-hooks.d"); err != nil {
		return fmt.Errorf("failed to create kernel-hooks.d: %w", err)
	}

	hookContent := fmt.Sprintf(`#!/bin/sh
FLAVOR="$1"
NEW_VERSION="$2"
tmpdir=$(mktemp -d)
trap 'rm -rf "${tmpdir}"' EXIT

booster build --force --kernel-version "${NEW_VERSION}-${FLAVOR}" "${tmpdir}/initramfs"

# Comment lines (the "Generated by FeralOS Installer" marker used for
# re-run detection) must not ride into the UKI kernel cmdline. The filter
# mirrors tpm's filterCmdlineComments: comments at any indent dropped,
# remaining lines joined with single spaces ($( ...) collapses the
# trailing newline), leading/trailing whitespace trimmed. Plain
# assignment + || true (a comment-only cmdline makes grep exit 1 — never
# abort the sequence) + an explicit empty guard BEFORE the build: a
# silently empty cmdline would ship a kernel with no boot parameters.
cmdline="$(grep -v '^[[:space:]]*#' /etc/kernel/cmdline | tr '\n' ' ' | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')" || true
[ -n "${cmdline}" ] || { echo 'refusing: /etc/kernel/cmdline is empty after comment filtering; refusing to build the UKI (apk kernel hook)' >&2; exit 1; }
output_dir="/boot/efi/Alpine"
output_name="linux-${FLAVOR}.efi"

mkdir -p "${output_dir}"

if [ -f %s ]; then
  efi-mkuki \
      -c "${cmdline}" \
      -o "${output_dir}/${output_name}" \
      "/boot/vmlinuz-${FLAVOR}" \
      %s \
      "${tmpdir}/initramfs"
elif [ -f %s ]; then
  efi-mkuki \
      -c "${cmdline}" \
      -o "${output_dir}/${output_name}" \
      "/boot/vmlinuz-${FLAVOR}" \
      %s \
      "${tmpdir}/initramfs"
else
  efi-mkuki \
      -c "${cmdline}" \
      -o "${output_dir}/${output_name}" \
      "/boot/vmlinuz-${FLAVOR}" \
      "${tmpdir}/initramfs"
fi

if [ -f "${output_dir}/${output_name}" ]; then
    cp -af "${output_dir}/${output_name}" "${output_dir}/linux-${FLAVOR}-backup.efi"
fi

mkdir -p "${output_dir}/../EFI/BOOT"
cp -af "${output_dir}/${output_name}" "${output_dir}/../EFI/BOOT/BOOTX64.EFI"

if [ -d /boot/efi2 ]; then
    cp -af /boot/efi/. /boot/efi2/
    mkdir -p /boot/efi2/EFI/BOOT
    cp -af "${output_dir}/${output_name}" /boot/efi2/EFI/BOOT/BOOTX64.EFI
fi
`, amdUcode, amdUcode, intelUcode, intelUcode)
	if err := shell.WriteFile(chroot, "/etc/kernel-hooks.d/50-booster.hook", []byte(hookContent+"\n"), 0644); err != nil {
		return fmt.Errorf("failed to write booster hook: %w", err)
	}
	if _, err := shell.ExecuteCmd(chroot, "chmod 755 /etc/kernel-hooks.d/50-booster.hook"); err != nil {
		return fmt.Errorf("failed to chmod booster hook: %w", err)
	}

	return nil
}
