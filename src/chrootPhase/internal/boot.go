package internal

import (
	"feralos/src/utils/config"
	"feralos/src/utils/shell"
	"fmt"
	"strings"
)

// SetupBoot writes booster config, kernel cmdline, and kernel hooks.
func SetupBoot(conf *config.Config) error {
	chroot := conf.Internal.ChrootDir
	u := conf.User

	// 1. Write the kernel cmdline fragments + assemble the final cmdline.
	// The installer writes ONLY the variables-dependent fragment
	// (cmdline.d/00-base.conf); package-shipped fragments
	// (hardening-config: 50-hardening.conf) and the debug fragment
	// (features/hardening.go: 99-debug.conf) land in the same directory,
	// and /usr/sbin/assemble-cmdline (assemble-cmdline package) joins them
	// into /etc/kernel/cmdline. The 50-booster kernel hook sources the
	// fragments live at every kernel upgrade, so a fragment upgrade is
	// picked up without touching the installer.
	fmt.Println("[INFO] Writing kernel cmdline fragments...")
	baseCmdline := strings.Join(u.KernelCmdline, " ")
	if u.EnableDebug {
		// Test-only: serial console lets the harness watch boot output and
		// answer the LUKS passphrase prompt. Real hardware stays clean.
		baseCmdline += " console=ttyS0,115200"
	}
	if u.EnableDinit {
		baseCmdline += " init=/usr/libexec/dinit/init"
		// Full service status trail (start/stop/fail, timestamps) to a file:
		// once login.target (runs-on-console) takes the console, dinit's own
		// output is inhibited — the file keeps the complete history. /run
		// exists from the initramfs (written before /var/log is mounted).
		// The dinit-boot-log service mirrors it to /var/log/dinit/boot.log
		// (vector source + logrotate). Upstream wrapper param:
		// dinit_log_file= -> --log-file.
		baseCmdline += " dinit_log_file=/run/dinit-boot.log"
	}
	if _, err := shell.ExecuteCmd(chroot, "mkdir -p /etc/kernel /etc/kernel/cmdline.d"); err != nil {
		return fmt.Errorf("failed to create /etc/kernel directories: %w", err)
	}
	if err := shell.WriteFile(chroot, "/etc/kernel/cmdline.d/00-base.conf", []byte(baseCmdline+"\n"), 0644); err != nil {
		return fmt.Errorf("failed to write base cmdline fragment: %w", err)
	}
	if _, err := shell.ExecuteCmd(chroot, "/usr/sbin/assemble-cmdline > /etc/kernel/cmdline"); err != nil {
		return fmt.Errorf("failed to assemble kernel cmdline: %w", err)
	}
	if _, err := shell.ExecuteCmd(chroot, "grep -q '[^[:space:]]' /etc/kernel/cmdline || { echo refusing: empty assembled cmdline; exit 1; }"); err != nil {
		return fmt.Errorf("assembled kernel cmdline is empty: %w", err)
	}
	if err := shell.WriteFileAppend(chroot, "/etc/kernel/cmdline", []byte("# Generated by FeralOS Installer\n"), 0644); err != nil {
		return fmt.Errorf("failed to append kernel cmdline marker: %w", err)
	}

	// 2. Write booster.yaml
	fmt.Println("[INFO] Writing booster configuration...")
	forceLoadModules := strings.Join(u.Modules, ",")
	// Tunables from the rules (boosterConfig): compression, extra_files,
	// mount_timeout and the network.dhcp sub-block (dhcp: false renders
	// "off" — enable_lvm/enable_mdraid/append_all_modaliases stay static).
	dhcp := "off"
	if conf.Internal.BoosterConfig.Network.Dhcp {
		dhcp = "on"
	}
	boosterYaml := fmt.Sprintf(`compression: %s
enable_lvm: false
enable_mdraid: false
network:
  dhcp: %s
modules_force_load: %s
mount_timeout: %s
extra_files: %s
append_all_modaliases: true`,
		conf.Internal.BoosterConfig.Compression, dhcp, forceLoadModules,
		conf.Internal.BoosterConfig.MountTimeout, conf.Internal.BoosterConfig.ExtraFiles)
	if err := shell.WriteFile(chroot, "/etc/booster.yaml", []byte(boosterYaml+"\n"), 0644); err != nil {
		return fmt.Errorf("failed to write booster.yaml: %w", err)
	}
	if err := shell.WriteFileAppend(chroot, "/etc/booster.yaml", []byte("# Generated by FeralOS Installer\n"), 0644); err != nil {
		return fmt.Errorf("failed to append booster.yaml marker: %w", err)
	}

	// 3. kernel hook: NO installer write anymore — the hook ships as
	// PACKAGE CONTENT (aports booster-hook: /etc/kernel-hooks.d/
	// 50-booster.hook, CPU-agnostic runtime microcode detection; user
	// decision 2026-11-28). The apk kernel trigger picks it up at the
	// linux-lts install in this very transaction.

	return nil
}
