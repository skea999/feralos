package btrfsStandardServer

import (
	"alpineInstaller/installer/utility"
	"fmt"
	"os"
	"strings"
)

// Se Subvolume non è definito in partitioning.go, scommenta queste righe:
/*
type Subvolume struct {
	Name    string
	Path    string
	Options string
	NoCoW   bool
}
*/

func GenerateFstabWithLabels(conf *utility.Config) error {
	u := conf.User
	i := conf.Internal

	// Controllo di sicurezza per evitare crash se la lista dischi è vuota
	if len(u.Disks) < 2 {
		return fmt.Errorf("layout btrfsStandardServer richiede almeno 2 dischi, trovati: %d", len(u.Disks))
	}

	fmt.Println("[INFO] Writing /etc/fstab for RAID1 Server Layout...")

	fstabPath := i.ChrootDir + "/etc/fstab"
	os.MkdirAll(i.ChrootDir+"/etc", 0755)

	file, err := os.Create(fstabPath)
	if err != nil {
		return fmt.Errorf("failed to create fstab: %w", err)
	}
	defer file.Close()

	getDiskSuffix := func(path string) string {
		parts := strings.Split(path, "/")
		return strings.ToUpper(parts[len(parts)-1])
	}

	file.WriteString("# Generated by Alpine Go Installer (RAID1 Server)\n")
	file.WriteString("# <file system> <mount point> <type> <options> <dump> <pass>\n\n")

	// 1. Subvolumes su RAID (Label: root)
	subvols := []Subvolume{
		{Name: "@", Path: "/", Options: "compress=zstd:3,autodefrag,ssd"},
		{Name: "@home", Path: "/home", Options: "compress=zstd:3,autodefrag,ssd"},
		{Name: "@opt", Path: "/opt", Options: "compress=zstd:3,autodefrag,ssd"},
		{Name: "@root", Path: "/root", Options: "compress=zstd:3,autodefrag,ssd"},
		{Name: "@srv", Path: "/srv", Options: "nodev,noexec,nosuid,nodatacow"},
		{Name: "@tmp", Path: "/tmp", Options: "noexec,nosuid,compress=zstd:3,autodefrag,ssd"},
		{Name: "@var", Path: "/var", Options: "compress=zstd:3,autodefrag,ssd"},
		{Name: "@var-log", Path: "/var/log", Options: "nodev,noexec,nosuid,nodatacow"},
		{Name: "@usr-local", Path: "/usr/local", Options: "compress=zstd:3,autodefrag,ssd"},
		{Name: "@swap", Path: "/swap", Options: "autodefrag,ssd,nodatacow"},
	}

	for _, s := range subvols {
		mountPoint := s.Path
		if mountPoint == "" {
			mountPoint = "/"
		}
		line := fmt.Sprintf("LABEL=root  %-20s  btrfs  subvol=%s,%s  0  0\n",
			mountPoint, s.Name, s.Options)
		file.WriteString(line)
	}

	// 2. Boot (Label: boot - definita su /dev/md0p1)
	file.WriteString("LABEL=boot  /boot                btrfs  defaults              0  2\n")

	// 3. EFI Partitions (Dinamiche dai primi due dischi della lista)
	// u.Disks[0] sostituisce u.Disk1 | u.Disks[1] sostituisce u.Disk2
	labelEfi1 := "EFI" + getDiskSuffix(u.Disks[0])
	labelEfi2 := "EFI" + getDiskSuffix(u.Disks[1])

	file.WriteString(fmt.Sprintf("LABEL=%-10s  /boot/efi            vfat   umask=0077,shortname=winnt  0  2\n", labelEfi1))
	file.WriteString(fmt.Sprintf("LABEL=%-10s  /boot/efi2           vfat   umask=0077,shortname=winnt  0  2\n", labelEfi2))

	// 4. External Data Partitions (Le quarte partizioni dei dischi fisici)
	suffix1 := strings.ToLower(getDiskSuffix(u.Disks[0]))
	suffix2 := strings.ToLower(getDiskSuffix(u.Disks[1]))

	file.WriteString(fmt.Sprintf("LABEL=data-%-5s  /data/data-%-10s  btrfs  compress=zstd:3       0  2\n", suffix1, suffix1))
	file.WriteString(fmt.Sprintf("LABEL=data-%-5s  /data/data-%-10s  btrfs  compress=zstd:3       0  2\n", suffix2, suffix2))

	return nil
}
